#!/usr/bin/env python3
"""Import the independent manual review of 217 new contact-sheet pictures.

Only proposal data. No pretrained detectors, training data changes, or human
review overrides. Requires the EXACT original contact-sheet ZIP generated by
Artes to bind each proposal to the right image ID and SHA256.
"""
import csv
import hashlib
import io
import json
import os
import shutil
import zipfile
from pathlib import Path

ROOT=Path.cwd() if __file__=="<stdin>" else Path(__file__).resolve().parents[1]
BASE=ROOT/".tmp/moderation-research-discovery"
IMAGES=BASE/"public-photo-candidates-20261010"
SHEETS=BASE/"Artes_nieuwe_contactvellen_20261012.zip"
EXPECTED_INDEX_SHA="36c00632651ff5d0056b2ec0c6c7aa3c9d068663146312da7e9b53754e0d65d3"
EXPECTED_IDS_SHA="be3afa2f91e6d40ba62a5cd2802e0273f144cef348f7836e726aae311a66c47b"
CODES="""
IK BK FK UK
BK UK IK FK
UK FK FK UK
FK UK FK FK
BK BK IK UK
UK FK FK FK
UK FK UK BK
BK FK UK BK
BK FK FK UK
UK UK UK UK
UK FK UK UK
MK UK MK UK
MK UK MK UK
UK UK UK BK
HK HN HN HK
HK HK HK HK
"""
NUDITY={"H":"none","U":"underwear_swimwear","I":"implied_nude",
        "B":"bare_buttocks","F":"female_bare_breasts",
        "G":"genitalia","M":"male_topless"}
CONTEXT={"K":"bdsm_kink","N":"none","S":"suggestive"}
NEEDS_DETAIL={3,7,15,16,19,24,25,29,30,35,36,39,43,46,48,53,55,56,60,61}

def main():
    if not SHEETS.is_file():
        raise SystemExit("Contact ZIP ontbreekt: "+str(SHEETS))
    with zipfile.ZipFile(SHEETS) as zipfile_obj:
        raw_index=zipfile_obj.read("index.csv")
    if hashlib.sha256(raw_index).hexdigest()!=EXPECTED_INDEX_SHA:
        raise SystemExit("Andere contactvellen dan visueel beoordeeld. Geen wijziging.")
    index=list(csv.DictReader(io.StringIO(raw_index.decode("utf-8-sig"))))
    if len(index)!=217 or hashlib.sha256("|".join(r["id"] for r in index).encode()).hexdigest()!=EXPECTED_IDS_SHA:
        raise SystemExit("Beelden/volgorde veranderd. Geen wijziging.")
    manifest=IMAGES/"unreviewed-images.jsonl"
    existing={x["id"]:x for x in (
        json.loads(line) for line in manifest.read_text(encoding="utf-8").splitlines() if line.strip()
    )}
    for row in index:
        stored=existing.get(row["id"])
        if not stored or stored.get("sha256")!=row["sha256"]:
            raise SystemExit("Bestand of hash komt niet overeen: "+row["id"])
    tokens=CODES.split()
    if len(tokens)!=64:raise SystemExit("Inconsistent handlabels")
    items=[]
    for i,record in enumerate(index,1):
        base={"id":record["id"],"basis":"assistant_manual_visual_review_of_contact_sheet",
              "assistantLabelConfidence":"medium","humanConfirmationRequired":True,
              "sourceFileSha256":record["sha256"],"authoritative":False,
              "originalReviewNeeded":False}
        if i<=64:
            n,c=tokens[i-1]
            base.update({"nudity":NUDITY[n],"sexualContext":CONTEXT[c],
                "ageSafety":"skip_minor_or_age_uncertain" if i==43 else "adult_clear",
                "originalReviewNeeded":i in NEEDS_DETAIL,
                "note":("Leeftijd van de afgebeelde persoon onvoldoende duidelijk."
                        if i==43 else "Controleer beeld op originele resolutie."
                        if i in NEEDS_DETAIL else "")})
        elif i<=112:
            base.update({"nudity":"","sexualContext":"","ageSafety":"",
                "reviewDisposition":"exclude_non_photographic_or_synthetic",
                "note":"Uitsluiten: anime/illustratie, geen echte fotografie."})
        else:
            base.update({"nudity":"underwear_swimwear" if i==172 else
                         "male_topless" if i==190 else "none",
                "sexualContext":"none","ageSafety":"not_required_nonadult_nonsexual",
                "note":"Gewone fotografie, geen seksuele handeling."})
        items.append(base)
    existing_file=IMAGES/"assistant-visual-prefill.json"
    old=json.loads(existing_file.read_text(encoding="utf-8"))
    if old.get("method")!="assistant_manual_visual_review" or len(old.get("items",[]))<458:
        raise SystemExit("De originele 458 suggesties zijn nog niet compleet. Geen wijziging.")
    old_by_id={x["id"]:x for x in old["items"]}
    overwritten=set(old_by_id).intersection(x["id"] for x in items)
    if overwritten:raise SystemExit("Er zijn al voorstellen voor een van deze IDs. Geen wijziging.")
    combined=dict(old)
    combined["items"]=old["items"]+items
    combined["humanConfirmationRequired"]=True
    combined["authoritative"]=False
    combined["trainingReady"]=False
    combined["existingDetectorModelUsed"]=False
    combined["excludedIllustrationsToConfirm"]=48
    backup=IMAGES/"assistant-visual-prefill.before-217.backup.json"
    if not backup.exists():shutil.copyfile(existing_file,backup)
    tmp=existing_file.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(combined,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    os.replace(tmp,existing_file)
    print("Samengevoegd:",len(combined["items"]),"voorstellen (458+217)")
    print("Inclusief 48 voorstel-uitsluitingen; niets automatisch bevestigd.")
    print("Bestaande persoonlijke beoordelingen en trainingsgegevens ongewijzigd.")

if __name__=="__main__":
    main()
